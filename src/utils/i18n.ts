export type TranslationKey = keyof typeof translations['ar'];

let currentLanguage: AppLanguage = 'ar';
const listeners: Array<(lang: AppLanguage) => void> = [];

export function getAppLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'ar';
  try {
    const saved = localStorage.getItem(STORAGE_KEY_LANG) as AppLanguage;
    if (saved && (saved === 'ar' || saved === 'en-GB' || saved === 'en-US')) {
      return saved;
    }
  } catch {}
  return 'ar';
}

export function setAppLanguage(lang: AppLanguage): void {
  currentLanguage = lang;
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem(STORAGE_KEY_LANG, lang);
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    } catch {}
  }
  listeners.forEach((fn) => fn(lang));
}

export function t(
  key: TranslationKey,
  paramsOrLang?: Record<string, string | number> | AppLanguage,
  lang?: AppLanguage
): string {
  let params: Record<string, string | number> | undefined;
  let activeLang: AppLanguage;

  if (typeof paramsOrLang === 'string') {
    activeLang = paramsOrLang;
  } else {
    params = paramsOrLang;
    activeLang = lang || currentLanguage || getAppLanguage();
  }

  const dict = translations[activeLang] || translations.ar;
  let text = (dict as any)[key] || translations.ar[key] || key;

  if (params && typeof text === 'string') {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
    });
  }

  return text;
}

export function useTranslation() {
  const [lang, setLang] = useState<AppLanguage>(() => getAppLanguage());

  useEffect(() => {
    currentLanguage = getAppLanguage();
    document.documentElement.lang = currentLanguage;
    document.documentElement.dir = currentLanguage === 'ar' ? 'rtl' : 'ltr';

    const handler = (newLang: AppLanguage) => {
      setLang(newLang);
    };
    listeners.push(handler);
    return () => {
      const idx = listeners.indexOf(handler);
      if (idx >= 0) listeners.splice(idx, 1);
    };
  }, []);

  return {
    t: (key: TranslationKey, params?: Record<string, string | number>) => t(key, params, lang),
    language: lang,
    setLanguage: setAppLanguage,
    isRTL: lang === 'ar',
    supportedLanguages: SUPPORTED_LANGUAGES,
  };
}
